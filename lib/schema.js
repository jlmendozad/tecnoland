const defaultStorefrontSettings = {
  eyebrow: 'TECNOLOGIA CURADA',
  title: 'El catalogo de Tecnoland ahora vive al frente.',
  description: 'Descubre productos activos, revisa colores, consulta disponibilidad y encuentra rapido lo que necesitas sin entrar al panel de administracion.',
  primaryCtaLabel: 'Ver catalogo'
};

// Crea o actualiza las tablas sin cargar datos de ejemplo ni usuarios.
// `db` puede ser un Pool o un Client de pg.
async function applySchema(db) {
  await db.query(`
    create table if not exists products (
      id bigint primary key generated by default as identity,
      name text not null,
      sku text not null unique,
      supplier_sku text not null default '',
      internal_sku text not null default '',
      active boolean not null default true,
      category text not null,
      product_color text not null default 'Sin especificar',
      cost numeric(12,2) not null default 0,
      price numeric(12,2) not null default 0,
      stock integer not null default 0 check (stock >= 0),
      threshold integer not null default 0 check (threshold >= 0),
      description text not null default '',
      emoji text not null default '📦',
      theme_color text not null default '#e8ecf5',
      created_at timestamptz not null default now(),
      updated_at timestamptz not null default now()
    );
    create table if not exists inventory_history (
      id bigint primary key generated always as identity,
      product_id bigint references products(id) on delete set null,
      sku text,
      action text not null,
      details jsonb not null default '{}'::jsonb,
      created_at timestamptz not null default now()
    );
    create index if not exists inventory_history_product_id_idx on inventory_history(product_id);
    create index if not exists inventory_history_created_at_idx on inventory_history(created_at desc);
    create table if not exists product_images (
      id bigint primary key generated by default as identity,
      product_id bigint not null references products(id) on delete cascade,
      image_url text not null,
      sort_order integer not null default 0,
      created_at timestamptz not null default now()
    );
    create index if not exists product_images_product_id_idx on product_images(product_id, sort_order, id);
    create table if not exists users (
      id bigint primary key generated by default as identity,
      full_name text not null,
      username text not null unique,
      role text not null default 'socio',
      password_salt text not null,
      password_hash text not null,
      active boolean not null default true,
      created_at timestamptz not null default now(),
      updated_at timestamptz not null default now()
    );
    create table if not exists orders (
      id bigint primary key generated by default as identity,
      order_number text not null unique,
      created_by_user_id bigint references users(id) on delete set null,
      customer_name text not null,
      customer_phone text not null default '',
      customer_address text not null default '',
      customer_note text not null default '',
      internal_note text not null default '',
      courier_company text not null default '',
      tracking_number text not null default '',
      delivery_method text not null default 'courier',
      payment_method text not null default 'transfer',
      status text not null default 'pending',
      subtotal numeric(12,2) not null default 0,
      discount numeric(12,2) not null default 0,
      total numeric(12,2) not null default 0,
      cost_total numeric(12,2) not null default 0,
      margin_total numeric(12,2) not null default 0,
      courier_handoff_at timestamptz,
      estimated_delivery_at timestamptz,
      delivered_at timestamptz,
      courier_amount_received numeric(12,2) not null default 0,
      receipt_info text not null default '',
      receipt_image_url text not null default '',
      created_at timestamptz not null default now(),
      updated_at timestamptz not null default now()
    );
    create table if not exists order_items (
      id bigint primary key generated by default as identity,
      order_id bigint not null references orders(id) on delete cascade,
      product_id bigint references products(id) on delete set null,
      sku text not null,
      product_name text not null,
      product_color text not null default '',
      quantity integer not null check (quantity > 0),
      unit_cost numeric(12,2) not null default 0,
      unit_price numeric(12,2) not null default 0,
      subtotal numeric(12,2) not null default 0
    );
    create index if not exists orders_created_at_idx on orders(created_at desc);
    create index if not exists order_items_order_id_idx on order_items(order_id);
    create table if not exists site_settings (
      id smallint primary key,
      storefront_banner jsonb not null default '{}'::jsonb,
      created_at timestamptz not null default now(),
      updated_at timestamptz not null default now()
    );
  `);
  await db.query(`alter table products add column if not exists supplier_sku text not null default ''`);
  await db.query(`alter table products add column if not exists internal_sku text not null default ''`);
  await db.query(`alter table products add column if not exists active boolean not null default true`);
  await db.query(`alter table orders add column if not exists courier_amount_received numeric(12,2) not null default 0`);
  await db.query(`alter table orders add column if not exists receipt_info text not null default ''`);
  await db.query(`alter table orders add column if not exists receipt_image_url text not null default ''`);
  await db.query(`update products set supplier_sku = case when supplier_sku = '' then sku else supplier_sku end where supplier_sku = ''`);
  await db.query(`update products set internal_sku = case when internal_sku = '' then sku else internal_sku end where internal_sku = ''`);
  await db.query(`update products set sku = internal_sku where internal_sku <> '' and sku <> internal_sku`);
  await db.query(
    `insert into site_settings (id, storefront_banner)
     values (1, $1::jsonb)
     on conflict (id) do nothing`,
    [JSON.stringify(defaultStorefrontSettings)]
  );
}

module.exports = { applySchema, defaultStorefrontSettings };
